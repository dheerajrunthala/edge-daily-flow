#!/usr/bin/env bash
# PostToolUse check after an edit to application code.
#
# CLAUDE.md requires lint and tests to pass before committing. Running them here means a
# break is reported in the turn that caused it, while the context is still on screen,
# rather than at commit time when it has to be re-derived.
#
# Never blocks. It prints and exits 0 — the point is a fast signal, and a formatter
# disagreement should not stop work mid-thought.
set -uo pipefail

payload=$(cat)

path=$(printf '%s' "$payload" | python3 -c '
import json, sys
try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(0)
ti = d.get("tool_input") or {}
print(ti.get("file_path") or "")
' 2>/dev/null)

case "$path" in
  *src/*.ts|*src/*.tsx|*supabase/functions/*.ts) ;;
  *) exit 0 ;;
esac

# Generated by the router plugin on every build; linting it is noise.
case "$path" in *routeTree.gen.ts|*integrations/supabase/types.ts) exit 0 ;; esac

cd "$(dirname "${BASH_SOURCE[0]}")/../.." || exit 0

errors=$(npm run lint 2>&1 | grep -E "^\s+[0-9]+:[0-9]+\s+error" | head -10)
if [ -n "$errors" ]; then
  echo "eslint errors introduced:" >&2
  echo "$errors" >&2
  echo "Run: npx prettier --write '$path' && npm run lint" >&2
fi

failures=$(npm test 2>&1 | grep -E "Tests .*failed|FAIL " | head -10)
if [ -n "$failures" ]; then
  echo "tests failing:" >&2
  echo "$failures" >&2
fi

exit 0
